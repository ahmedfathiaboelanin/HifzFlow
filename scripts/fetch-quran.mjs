// Fetch the full Uthmani text from AlQuran Cloud and commit it as local JSON.
// Also generates src/data/mushaf.ts (per-page 1-604 + juz mapping) from the
// per-ayah page/juz fields in the API response, and verifies the dataset.
//
// Usage: node scripts/fetch-quran.mjs
// Output: src/data/quran.json, src/data/mushaf.ts
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(ROOT, 'src', 'data');
const URL = 'https://api.alquran.cloud/v1/quran/quran-uthmani';

const res = await fetch(URL);
if (!res.ok) throw new Error(`AlQuran Cloud request failed: ${res.status}`);
const json = await res.json();
if (json.code !== 200 || !json.data?.surahs) throw new Error('Unexpected API response shape');

const surahs = json.data.surahs;

// ---- Verification -------------------------------------------------------
const totalAyahs = surahs.reduce((n, s) => n + s.ayahs.length, 0);
console.log(`Surahs: ${surahs.length} (expected 114)`);
console.log(`Ayahs:  ${totalAyahs} (expected 6236)`);
if (surahs.length !== 114) throw new Error('Surah count mismatch');
if (totalAyahs !== 6236) throw new Error('Ayah count mismatch');

const missingPage = surahs.flatMap((s) => s.ayahs).filter((a) => !a.page || !a.juz);
if (missingPage.length > 0) throw new Error(`${missingPage.length} ayahs missing page/juz`);

const pages = new Set(surahs.flatMap((s) => s.ayahs.map((a) => a.page)));
const minPage = Math.min(...pages);
const maxPage = Math.max(...pages);
console.log(`Pages:  ${minPage}–${maxPage} (${pages.size} distinct, expected 1–604 / 604)`);
if (minPage !== 1 || maxPage !== 604 || pages.size !== 604) throw new Error('Page range mismatch');

// ---- Spot checks ---------------------------------------------------------
const ayah = (surahNo, ayahNo) => {
  const s = surahs.find((x) => x.number === surahNo);
  return s.ayahs.find((a) => a.numberInSurah === ayahNo);
};
const p1 = surahs[0].ayahs.every((a) => a.page === 1);
const p2 = [1, 2, 3, 4, 5].every((n) => ayah(2, n).page === 2);
const juz30Start = ayah(78, 1);
console.log(`p1 Al-Fatiha all on page 1: ${p1}`);
console.log(`p2 Al-Baqarah 1-5 on page 2: ${p2}`);
console.log(`Juz 30 starts at An-Naba 1: page=${juz30Start.page} juz=${juz30Start.juz} (expected page 582, juz 30)`);
if (!p1 || !p2) throw new Error('Spot check failed');
if (juz30Start.page !== 582 || juz30Start.juz !== 30) throw new Error('Juz 30 spot check failed');

// ---- Trimmed local JSON ---------------------------------------------------
const trimmed = {
  source: 'AlQuran Cloud quran-uthmani (Tanzil text)',
  fetchedAt: new Date().toISOString(),
  surahs: surahs.map((s) => ({
    number: s.number,
    name: s.name,
    englishName: s.englishName,
    englishNameTranslation: s.englishNameTranslation,
    revelationType: s.revelationType,
    ayahs: s.ayahs.map((a) => ({
      n: a.numberInSurah,
      text: a.text,
      page: a.page,
      juz: a.juz,
    })),
  })),
};
mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(join(OUT_DIR, 'quran.json'), JSON.stringify(trimmed));

// ---- Mushaf page map -------------------------------------------------------
// For each mushaf page 1..604: juz + the surah/ayah ranges starting on it.
const byPage = new Map();
for (const s of surahs) {
  for (const a of s.ayahs) {
    if (!byPage.has(a.page)) byPage.set(a.page, []);
    byPage.get(a.page).push({ surah: s.number, ayah: a.numberInSurah, juz: a.juz });
  }
}
const pageInfo = [];
for (let p = 1; p <= 604; p++) {
  const list = byPage.get(p) ?? [];
  const juz = list.length ? list[0].juz : pageInfo.length ? pageInfo[pageInfo.length - 1].juz : 1;
  // Group consecutive ayahs of the same surah into ranges.
  const ranges = [];
  for (const item of list) {
    const last = ranges[ranges.length - 1];
    if (last && last.surah === item.surah && last.to === item.ayah - 1) last.to = item.ayah;
    else ranges.push({ surah: item.surah, from: item.ayah, to: item.ayah });
  }
  pageInfo.push({ page: p, juz, ranges });
}

const surahMeta = surahs.map((s) => ({
  number: s.number,
  name: s.name,
  englishName: s.englishName,
  englishNameTranslation: s.englishNameTranslation,
  revelationType: s.revelationType,
  ayahs: s.ayahs.length,
  startPage: s.ayahs[0].page,
  endPage: s.ayahs[s.ayahs.length - 1].page,
  startJuz: s.ayahs[0].juz,
}));

const mushafTs = `// Generated by scripts/fetch-quran.mjs from AlQuran Cloud quran-uthmani.
// Do not edit by hand — re-run the script. 604 Madani mushaf pages.
export interface PageRange { surah: number; from: number; to: number }
export interface PageInfo { page: number; juz: number; ranges: PageRange[] }
export interface SurahMeta {
  number: number; name: string; englishName: string;
  englishNameTranslation: string; revelationType: string; ayahs: number;
  startPage: number; endPage: number; startJuz: number;
}
export const SURAHS: SurahMeta[] = ${JSON.stringify(surahMeta)};
export const PAGES: PageInfo[] = ${JSON.stringify(pageInfo)};
`;
writeFileSync(join(OUT_DIR, 'mushaf.ts'), mushafTs);
console.log('Wrote src/data/quran.json and src/data/mushaf.ts — verification passed.');
